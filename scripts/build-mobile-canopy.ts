import { registerHooks } from 'node:module';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { BananaArtwork } from '../src/BananaLoader';
// Rendering the real component keeps silhouettes, veins, depth and gap fills identical.
const hook = registerHooks({
  load(url, context, next) {
    if (url.endsWith('.css')) return { format: 'module', source: '', shortCircuit: true };
    return next(url, context);
  },
});
const { BotanicalCanopy } = await import('../src/BotanicalCanopy');
const markup = renderToStaticMarkup(createElement(BotanicalCanopy));
hook.deregister();
const match = markup.match(/<svg[^>]*class="botanical-art"[\s\S]*?<\/svg>/);
if (!match) throw new Error('No se encontró la copa original.');
const svg = match[0]
  .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
  .replace('viewBox="0 0 1920 170"', 'viewBox="320 0 1280 170"')
  .replace('><defs>', '><style>.botanical-backing{display:none}</style><defs>');
const hash = createHash('sha256').update(svg).digest('hex').slice(0, 10);
await mkdir('public/canopy', { recursive: true });
const paths: string[] = [];
for (const density of [1, 2, 3]) {
  const path = `/canopy/mobile-${hash}-${density}x.webp`;
  await sharp(Buffer.from(svg), { density: 72 * density * 1.2 })
    .resize(1536 * density, 204 * density)
    .webp({ lossless: true, effort: 6 })
    .toFile('public' + path);
  paths.push(path);
}
await writeFile(
  'src/canopy-assets.ts',
  '// Generated by scripts/build-mobile-canopy.ts. Lossless, same original SVG.\nexport const mobileCanopy = ' +
    JSON.stringify({
      src: paths[0],
      srcSet: paths.map((path, i) => `${path} ${i + 1}x`).join(', '),
    }) +
    ';\n',
);
console.log('Copa móvil generada en tres densidades, sin pérdida.');

await writeFile('public/banana-loading.svg', renderToStaticMarkup(createElement(BananaArtwork)).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" '));
